import os

from langchain_groq import ChatGroq
from langchain_core.messages import SystemMessage, HumanMessage

from src.state import ResearchState


model = ChatGroq(
    model="llama-3.3-70b-versatile",
    api_key=os.getenv("GROQ_API_KEY_1")
)


def newsletter_writer(state: ResearchState):

    summaries = state["summaries"]

    paper_content = ""

    for paper in summaries:
        paper_content += f"""
Title: {paper.title}

Problem:
{paper.problem}

Approach:
{paper.approach}

Findings:
{paper.findings}

Why it matters:
{paper.why_it_matters}

-----------------------------
"""

    response = model.invoke([
        SystemMessage(
            content="""
You are an AI research newsletter writer.

Create a professional HTML email newsletter for AI developers
and students.

Use ONLY the provided research summaries.
Do not invent information.

Return valid HTML only.

Design requirements:

- Maximum content width around 700px
- Clean modern newsletter layout
- White background
- Professional typography
- Clear spacing between sections

Newsletter structure:

1. Header
   - "AI Research Weekly"
   - Short subtitle about this week's research

2. Introduction
   - 2-3 sentence overview

3. Research Papers

   For each paper include:
   - Paper title
   - What problem does it solve?
   - How does it work?
   - Key findings
   - Why it matters

4. Key Takeaways
   - Short bullet list of the most important insights

5. Footer
   - "Generated by AI Research Newsletter"

Use email-safe inline CSS.

Do NOT include markdown.
Do NOT include ```html code fences.
Return only the final HTML.
"""
        ),

        HumanMessage(
            content=f"""
Create this week's newsletter from these research summaries:

{paper_content}
"""
        )
    ])

    return {
        "email_content": response.content
    }